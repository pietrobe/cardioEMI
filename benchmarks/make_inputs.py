"""Generate the .yml inputs of the paper benchmarks (standard library only).

    python3 benchmarks/make_inputs.py
    python3 benchmarks/make_inputs.py --list table8,table9   # runs and configs of some tables

Writes benchmarks/inputs/<run>/<config>.yml, with <run> = <model>_n<nodes>
(e.g. B2_n4) or "smoke", and <config> = <gpu|cpu>_<cg|gmres>_amg. Paths inside
the yml files are relative to the run directory created by benchmarks/env.sh
(enter_rundir), where meshes/ and results/ are symlinks.

Runs and the tables they feed (nodes as defined in the paper: one GH200 or
144 CPU cores):

    Table 4  assembly, strong scaling   A1 and B1 at n = 1, 2, 4, 8          (AMG-CG runs)
    Table 5  assembly, weak scaling     A1-A4 and B1-B4 at n = 1, 2, 4, 8    (AMG-CG runs)
    Table 6  solver, strong scaling     A1 at n = 1, 2, 4, 8                 GPU Jacobi-CG, AMG-CG
    Table 7  solver, weak scaling       A1-A4 at n = 1, 2, 4, 8              GPU Jacobi-CG, AMG-CG
    Table 8  solver, strong scaling     B1 and B2 at n = 1, 2, 4, 8          AMG-CG
    Table 9  solver, weak scaling       B1-B4 at n = 1, 2, 4, 8              AMG-CG and AMG-GMRES

The assembly times come from the same runs as the solver times (main.py
measures both). Solver options as in the appendix of the paper:
  - Model A: AMG with the default coarsening of each architecture, l1-scaled
    SOR/Jacobi smoother, strong threshold 0.25, no aggressive coarsening;
    point-Jacobi CG on GPU only;
  - Model B: the same BoomerAMG on CPU and GPU (PMIS, ext+i, Chebyshev on every
    level, no C/F relaxation, no aggressive coarsening, min coarse size 2).
CG uses homogeneous Neumann conditions and the constant nullspace, GMRES one
Dirichlet point.
"""

import sys
from pathlib import Path

TIME_STEPS = 100
SMOKE_TIME_STEPS = 3
KSP_MAX_IT = 2000       # bound the cost of a stagnating solve
JACOBI_MAX_IT = 30000   # Jacobi-CG needs about 1800-2300 iterations on Model A

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "inputs"

# Mesh files in $CARDIO_MESH_DIR (meshes/ in the run directory). Model A is
# generated by emigrid_mesh/generate_model_A.sh, Model B (cleaned meshes) is
# available from the authors on request.
MESHES = {
    "A1": "meshes/A1", "A2": "meshes/A2", "A3": "meshes/A3", "A4": "meshes/A4",
    "B1": "meshes/millie-5_clean", "B2": "meshes/millie-12_clean",
    "B3": "meshes/millie-22_clean", "B4": "meshes/millie-47_clean",
}
NODES = (1, 2, 4, 8)
WEAK_A = [("A1", 1), ("A2", 2), ("A3", 4), ("A4", 8)]
WEAK_B = [("B1", 1), ("B2", 2), ("B3", 4), ("B4", 8)]

# table -> {run: [config suffixes]}; the configurations of a run are the union
# over the tables that use it (benchmarks/submit.sh reads the same lists)
TABLES = {
    "table4": {f"{m}_n{n}": ["cg_amg"] for m in ("A1", "B1") for n in NODES},
    "table5": {f"{m}_n{n}": ["cg_amg"] for m, n in WEAK_A + WEAK_B},
    "table6": {f"A1_n{n}": ["cg_amg", "cg_jacobi"] for n in NODES},
    "table7": {f"{m}_n{n}": ["cg_amg", "cg_jacobi"] for m, n in WEAK_A},
    "table8": {f"{m}_n{n}": ["cg_amg"] for m in ("B1", "B2") for n in NODES},
    "table9": {f"{m}_n{n}": ["cg_amg", "gmres_amg"] for m, n in WEAK_B},
}

KRYLOV = {"cg_amg": dict(ksp="cg", dirichlet=0, pc="hypre"),
          "gmres_amg": dict(ksp="gmres", dirichlet=1, pc="hypre"),
          "cg_jacobi": dict(ksp="cg", dirichlet=0, pc="jacobi")}
# configurations run on one family only (paper: Jacobi on GPU only)
FAMILIES = {"cg_jacobi": ("gpu",)}

AMG_A = {
    "pc_hypre_boomeramg_relax_type_all": "l1scaled-SOR/Jacobi",
    "pc_hypre_boomeramg_agg_nl": 0,
    "pc_hypre_boomeramg_strong_threshold": 0.25,
}
AMG_B = {
    "pc_hypre_boomeramg_coarsen_type": "PMIS",
    "pc_hypre_boomeramg_interp_type": "ext+i",
    "pc_hypre_boomeramg_relax_type_all": "Chebyshev",
    "pc_hypre_boomeramg_relax_type_coarse": "Chebyshev",
    "pc_hypre_boomeramg_no_CF": "true",
    "pc_hypre_boomeramg_agg_nl": 0,
    "pc_hypre_boomeramg_strong_threshold": 0.25,
    "pc_hypre_boomeramg_min_coarse_size": 2,
    "pc_hypre_boomeramg_print_statistics": 1,   # AMG hierarchy in the log
}

TEMPLATE = """\
# Generated by benchmarks/make_inputs.py -- do not edit by hand
mesh_file             : "{mesh}.xdmf"
tags_dictionary_file  : "{mesh}.pickle"
mesh_conversion_factor: 0.0001   # um -> cm
ECS_TAG  : 0
fem_order: 1
cuda     : {cuda}

# Temporal parameters
dt         : 0.005
time_steps : {steps}

# Physical parameters
C_M    : 1
sigma_i: 5
sigma_e: 1
R_g    : 0.003

# Boundary conditions (0 = pure Neumann + constant nullspace)
Dirichlet_points: {dirichlet}

# Initial membrane potential
v_init: "-80 * (x[0] > 0.0)"

# Ionic model
ionic_model:
  intra_intra: "Passive"
  intra_extra: "AP"

# Solver
ksp_type: "{ksp}"
pc_type : "{pc}"
ksp_rtol: 1.0e-7
petsc_opts:
  ksp_max_it: {max_it}
{amg}
# Output
save_output     : False
save_performance: True
verbose         : False
out_name        : "results/{run}/{config}"
"""


def amg_block(opts):
    return "".join(f'  {k}: "{v}"\n' if isinstance(v, str) else f"  {k}: {v}\n" for k, v in opts.items())


def write(run, mesh, suffixes, steps, amg):
    files = []
    for family, cuda in (("gpu", True), ("cpu", False)):
        for s in suffixes:
            if family not in FAMILIES.get(s, ("gpu", "cpu")):
                continue
            config = f"{family}_{s}"
            k = KRYLOV[s]
            path = OUT / run / f"{config}.yml"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(TEMPLATE.format(
                mesh=mesh, cuda=cuda, steps=steps, ksp=k["ksp"], dirichlet=k["dirichlet"], pc=k["pc"],
                max_it=JACOBI_MAX_IT if k["pc"] == "jacobi" else KSP_MAX_IT,
                amg=amg_block(amg) if k["pc"] == "hypre" else "", run=run, config=config))
            files.append(path)
    return files


def runs(tables=TABLES):
    """{run: sorted config suffixes} over the given tables."""
    out = {}
    for name in tables:
        for run, suffixes in TABLES[name].items():
            out.setdefault(run, set()).update(suffixes)
    return {run: sorted(s) for run, s in sorted(out.items())}


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--list":
        # used by benchmarks/submit.sh: one line "<run> <suffix> ..." per run
        selected = list(TABLES) if sys.argv[2] == "all" else sys.argv[2].split(",")
        unknown = [t for t in selected if t not in TABLES]
        if unknown:
            sys.exit(f"unknown table(s) {', '.join(unknown)}: choose among {', '.join(TABLES)} or all")
        for run, suffixes in runs(selected).items():
            print(run, *suffixes)
        sys.exit(0)
    files = []
    for run, suffixes in runs().items():
        model = run.split("_n")[0]
        files += write(run, MESHES[model], suffixes, TIME_STEPS, AMG_A if model.startswith("A") else AMG_B)
    # installation check on the small mesh shipped with the repository
    files += write("smoke", "data/robin-h21-25", ["cg_amg", "gmres_amg"], SMOKE_TIME_STEPS, AMG_B)
    for f in files:
        print(f.relative_to(ROOT.parent))
